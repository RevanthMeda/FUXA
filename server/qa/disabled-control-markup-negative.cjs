'use strict';
const assert = require('node:assert/strict');
const path = require('node:path');
const Module = require('node:module');
const { execFileSync } = require('node:child_process');
const root = process.cwd();
const target = path.join(root, 'runtime/utils.js');
const current = require(target);
const original = new Module(target, module);
original.filename = target;
original.paths = Module._nodeModulePaths(path.dirname(target));
original._compile(execFileSync('git', ['show', '874a68a59c39baa72fb098e97280d1dcd82b83bf:server/runtime/utils.js'], {cwd: root, encoding: 'utf8'}), target);
const fixed = current.domStringSetAttribute;
current.domStringSetAttribute = original.exports.domStringSetAttribute;
const Mocha = require(path.join(root, 'node_modules/mocha'));
const expected = ['multiple inputs', 'mixed controls preserve earlier changes', 'nested markup and closing tags', 'case and multiline attributes', 'self-closing controls', 'quoted angle brackets', 'tag name boundaries', 'comments and CDATA', 'raw text elements', 'existing disabled attributes', 'is idempotent when the same fragment is filtered twice', 'disables all controls without corrupting the project or its admin copy', 'preserves markup when retrieving a restricted single view repeatedly'].sort();
const failed = [];
const mocha = new Mocha({ reporter: 'dot', timeout: 10000 });
mocha.addFile(path.join(root, 'test/help/disabledControlMarkup.test.js'));
const runner = mocha.run(failures => {
    current.domStringSetAttribute = fixed;
    assert.equal(failures, 13);
    assert.equal(runner.stats.tests, 15);
    assert.equal(runner.stats.passes, 2);
    assert.equal(runner.stats.pending, 0);
    assert.deepEqual(failed.sort(), expected);
    console.log('Original markup helper rejected by 13 exact regressions; two compatibility cases pass.');
});
runner.on('fail', test => failed.push(test.title));
