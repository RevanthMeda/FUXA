'use strict';
const assert = require('node:assert/strict');
const path = require('node:path');
const Module = require('node:module');
const { execFileSync } = require('node:child_process');
const root = process.cwd();
const target = path.join(root, 'runtime/utils.js');
const current = require(target);
const original = new Module(target, module);
original.filename = target;
original.paths = Module._nodeModulePaths(path.dirname(target));
original._compile(execFileSync('git', ['show', '874a68a59c39baa72fb098e97280d1dcd82b83bf:server/runtime/utils.js'], {cwd: root, encoding: 'utf8'}), target);
const splitter = process.argv[2] === 'splitter';
const method = splitter ? 'domStringSplitter' : 'domStringSetAttribute';
const fixed = current[method];
current[method] = original.exports[method];
const Mocha = require(path.join(root, 'node_modules/mocha'));
const attributeFailures = ['multiple inputs', 'mixed controls preserve earlier changes', 'nested markup and closing tags', 'case and multiline attributes', 'self-closing controls', 'quoted angle brackets', 'tag name boundaries', 'comments and CDATA', 'raw text elements', 'existing disabled attributes', 'is idempotent when the same fragment is filtered twice', 'disables all controls without corrupting the project or its admin copy', 'preserves markup when retrieving a restricted single view repeatedly'].sort();
const splitterFailures = ["ignores opening-tag lookalikes in text containers and longer names", "keeps the whole input before when only a commented opening tag exists", "stops a self-closing fragment before unrelated controls", "does not treat a longer closing tag name as the fragment boundary", "disables controls after a commented closing tag through both project paths", "disables controls after a CDATA closing tag through both project paths", "disables controls after a quoted closing tag through both project paths", "disables controls after a script closing-tag literal through both project paths", "disables controls after a nested foreignObject through both project paths"];
const expected = (splitter ? splitterFailures : attributeFailures).sort();
const failed = [];
const mocha = new Mocha({ reporter: 'dot', timeout: 10000 });
if (!splitter) mocha.grep(/foreignObject fragment boundaries|disables controls after/).invert();
mocha.addFile(path.join(root, 'test/help/disabledControlMarkup.test.js'));
const runner = mocha.run(failures => {
    current[method] = fixed;
    assert.equal(failures, splitter ? 9 : 13);
    assert.equal(runner.stats.tests, splitter ? 24 : 15);
    assert.equal(runner.stats.passes, splitter ? 15 : 2);
    assert.equal(runner.stats.pending, 0);
    assert.deepEqual(failed.sort(), expected);
    console.log(splitter ? 'Original splitter rejected by nine exact regressions; 15 compatibility cases pass.' : 'Original markup helper rejected by 13 exact regressions; two compatibility cases pass.');
});
runner.on('fail', test => failed.push(test.title));
